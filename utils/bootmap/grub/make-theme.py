#!/usr/bin/env python3
"""Make the bootmap GRUB theme: the boot menu in the treemap's style.

    grub/make-theme.py <out dir> [--scale N] [--palette NAME]

GRUB is the "loader" stage of the treemap, so the theme uses the loader
colour of the palette (src/render/color.zig). A menu entry is a box: dim
with coloured text when not selected (a pending box), filled with black
text when selected (a full box, inverse ink). The timeout is a box that
fills. The text is the treemap's 6x8 font (src/render/font_data.zig),
made into a GRUB font with grub-mkfont. --scale 2 doubles every pixel, for
a HiDPI screen.

The output is the theme folder for /boot/grub/themes/bootmap/.
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def palette(name):
    """The stops of a palette, from src/render/color.zig."""
    src = open(os.path.join(ROOT, "src/render/color.zig")).read()
    m = re.search(r'\.name = "' + re.escape(name) + r'", \.stops = &\.\{([^}]*)\}', src)
    if not m:
        sys.exit(f"make-theme: no palette {name} in color.zig")
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{6})", m.group(1))]


def font_rows():
    """The 6x8 glyphs, from src/render/font_data.zig."""
    src = open(os.path.join(ROOT, "src/render/font_data.zig")).read()
    blk = src[src.index("pub const f6x8_rows"):]
    return [int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", blk)][: 256 * 8]


def scale_rgb(c, pct):
    return tuple(((c >> s) & 0xFF) * pct // 100 for s in (16, 8, 0))


def rgb(c):
    return ((c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF)


def hexc(t):
    return "#%02x%02x%02x" % t


def png(path, w, h, color):
    """A solid PNG of w x h."""
    raw = b"".join(b"\x00" + bytes(color) * w for _ in range(h))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def bdf(path, scale):
    """The 6x8 font as BDF (ASCII 32..126), each pixel scale x scale."""
    rows = font_rows()
    w, h = 6 * scale, 8 * scale
    nbytes = (w + 7) // 8
    out = ["STARTFONT 2.1", f"FONT -bootmap-bootmap-medium-r-normal--{h}-{h * 10}-75-75-c-{w * 10}-iso10646-1",
           # 72 dpi and PIXEL_SIZE: FreeType then makes the strike h pixels, so
           # grub-mkfont -s h finds it at every scale.
           f"SIZE {h} 72 72", f"FONTBOUNDINGBOX {w} {h} 0 {-scale}", "STARTPROPERTIES 5",
           f"PIXEL_SIZE {h}", "RESOLUTION_X 72", "RESOLUTION_Y 72",
           f"FONT_ASCENT {h - scale}", f"FONT_DESCENT {scale}", "ENDPROPERTIES", f"CHARS {126 - 32 + 1}"]
    for ch in range(32, 127):
        out += [f"STARTCHAR c{ch}", f"ENCODING {ch}", f"SWIDTH {w * 72} 0", f"DWIDTH {w} 0",
                f"BBX {w} {h} 0 {-scale}", "BITMAP"]
        for y in range(8):
            bits = rows[ch * 8 + y] >> 2  # 6 bits, most significant first
            line = 0
            for x in range(6):
                if (bits >> (5 - x)) & 1:
                    for k in range(scale):
                        line |= 1 << (w - 1 - (x * scale + k))
            line <<= nbytes * 8 - w
            for _ in range(scale):
                out.append(f"{line:0{nbytes * 2}X}")
        out.append("ENDCHAR")
    out.append("ENDFONT")
    open(path, "w").write("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--scale", type=int, default=1)
    ap.add_argument("--palette", default="dataviz")
    a = ap.parse_args()
    s = a.scale
    os.makedirs(a.out, exist_ok=True)

    stops = palette(a.palette)
    loader = stops[1 % len(stops)]  # stage 1: the loader
    full = rgb(loader)
    dim = scale_rgb(loader, 25)  # empty=dim: the box colour at 25 %
    black = (0, 0, 0)

    # The font: BDF from our glyphs, then grub-mkfont.
    bdf_path = os.path.join(a.out, "bootmap.bdf")
    bdf(bdf_path, s)
    font_name = f"bootmap Regular {8 * s}"
    subprocess.run(["grub-mkfont", "-s", str(8 * s), "-n", "bootmap", "-o",
                    os.path.join(a.out, "bootmap.pf2"), bdf_path], check=True)
    os.remove(bdf_path)

    # 9-slice boxes, 1 logical pixel per piece: a menu entry, the selected
    # entry, and the timeout bar. GRUB draws the border pieces outside the
    # entry, so item_spacing is 3 pixels: 1 border, 1 gap (black), 1 border.
    for prefix, color in (("item", dim), ("select", full), ("bar", dim), ("bar_hl", full)):
        for piece in ("nw", "n", "ne", "w", "c", "e", "sw", "s", "se"):
            png(os.path.join(a.out, f"{prefix}_{piece}.png"), s, s, color)

    line = 9 * s  # one 6x8 line and 1 px of leading
    pad = 1 * s
    theme = f"""# GENERATED by grub/make-theme.py (palette {a.palette}, scale {s}). The
# boot menu in the treemap's style: GRUB is the loader stage.
desktop-color: "#000000"
title-text: ""
terminal-font: "{font_name}"
terminal-box: "item_*.png"

# The stage title, as the treemap draws an area title.
+ label {{
    left = {pad}
    top = 0
    width = 100%
    height = {line}
    text = "loader"
    font = "{font_name}"
    color = "{hexc(full)}"
}}

+ boot_menu {{
    left = {pad}
    top = {line}
    width = 100%-{2 * pad}
    height = 100%-{4 * line}
    item_font = "{font_name}"
    selected_item_font = "{font_name}"
    item_color = "{hexc(full)}"
    selected_item_color = "{hexc(black)}"
    item_height = {3 * line}
    item_padding = {pad}
    item_spacing = {3 * pad}
    icon_width = 0
    icon_height = 0
    item_icon_space = 0
    item_pixmap_style = "item_*.png"
    selected_item_pixmap_style = "select_*.png"
    scrollbar = false
}}

# The timeout: a box that fills.
+ progress_bar {{
    id = "__timeout__"
    left = {pad}
    top = 100%-{2 * line}
    width = 100%-{2 * pad}
    height = {2 * line}
    font = "{font_name}"
    text_color = "{hexc(black)}"
    text = "@TIMEOUT_NOTIFICATION_MIDDLE@"
    bar_style = "bar_*.png"
    highlight_style = "bar_hl_*.png"
}}
"""
    open(os.path.join(a.out, "theme.txt"), "w").write(theme)
    print(f"make-theme: {a.out} (palette {a.palette}, scale {s}, font {font_name})")


if __name__ == "__main__":
    main()
