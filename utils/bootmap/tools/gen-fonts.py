#!/usr/bin/env python3
"""Generate the bitmap font tables from the kernel's lib/fonts.

    tools/gen-fonts.py <linux source dir>          # writes both files:
        src/render/font_data.zig   (the replay, the CLI, the daemon)
        kernel/bootmap_font.h      (kernel/bootmap.c)

kernel/bootmap.c draws with the same fonts (lib/fonts in the kernel), so the
replay and the kernel draw the same glyph pixels. Each glyph row is one byte,
most significant bit first.
"""
import re
import sys

FONTS = [("mini_4x6", "font_mini_4x6.c", 4, 6), ("f6x8", "font_6x8.c", 6, 8)]


def glyph_bytes(path):
    text = open(path).read()
    start = text.index("FONTDATAMAX, 0 }, {")
    end = text.index("};", start)
    body = re.sub(r"/\*.*?\*/", "", text[start + len("FONTDATAMAX, 0 }, {"):end], flags=re.S)
    return [int(t, 16) for t in re.findall(r"0x[0-9a-fA-F]+", body)]


def c_header(fonts):
    out = [
        "/* SPDX-License-Identifier: GPL-2.0 */",
        "/* GENERATED by tools/gen-fonts.py from the kernel's lib/fonts. Do not edit.",
        " * The same glyphs as src/render/font_data.zig. One byte per row, most",
        " * significant bit first. */",
        "#ifndef BOOTMAP_FONT_H",
        "#define BOOTMAP_FONT_H",
        "",
    ]
    for name, w, h, data in fonts:
        out.append(f"#define BOOTMAP_FONT_{name.upper()}_W {w}")
        out.append(f"#define BOOTMAP_FONT_{name.upper()}_H {h}")
        out.append(f"static const unsigned char bootmap_font_{name}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            out.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    src = sys.argv[1]
    here = __import__("os").path.dirname(__import__("os").path.abspath(__file__))
    root = __import__("os").path.dirname(here)
    fonts = []
    out = [
        "//! GENERATED by tools/gen-fonts.py from the Linux kernel's lib/fonts. Do not edit.",
        "//! The glyph data is from the kernel (GPL-2.0). 256 glyphs, one byte per row,",
        "//! most significant bit first.",
        "",
    ]
    for name, file, w, h in FONTS:
        data = glyph_bytes(f"{src}/lib/fonts/{file}")
        if len(data) != 256 * h:
            sys.exit(f"gen-fonts: {file}: {len(data)} bytes, expected {256 * h}")
        fonts.append((name, w, h, data))
        out.append(f"pub const {name}_w: u8 = {w};")
        out.append(f"pub const {name}_h: u8 = {h};")
        out.append(f"pub const {name}_rows = [_]u8{{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    with open(f"{root}/src/render/font_data.zig", "w") as f:
        f.write("\n".join(out) + "\n")
    with open(f"{root}/kernel/bootmap_font.h", "w") as f:
        f.write(c_header(fonts))


if __name__ == "__main__":
    main()
