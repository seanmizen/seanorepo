#!/usr/bin/env python3
"""Generate src/render/font_data.zig from the kernel's bitmap fonts.

    tools/gen-fonts.py <linux source dir> > src/render/font_data.zig

kernel/bootmap.c draws with the same fonts (lib/fonts in the kernel), so the
replay and the kernel draw the same glyph pixels. Each glyph row is one byte,
most significant bit first.
"""
import re
import sys

FONTS = [("mini_4x6", "font_mini_4x6.c", 4, 6), ("f6x8", "font_6x8.c", 6, 8)]


def glyph_bytes(path):
    text = open(path).read()
    start = text.index("FONTDATAMAX, 0 }, {")
    end = text.index("};", start)
    body = re.sub(r"/\*.*?\*/", "", text[start + len("FONTDATAMAX, 0 }, {"):end], flags=re.S)
    return [int(t, 16) for t in re.findall(r"0x[0-9a-fA-F]+", body)]


def main():
    src = sys.argv[1]
    out = [
        "//! GENERATED by tools/gen-fonts.py from the Linux kernel's lib/fonts. Do not edit.",
        "//! The glyph data is from the kernel (GPL-2.0). 256 glyphs, one byte per row,",
        "//! most significant bit first.",
        "",
    ]
    for name, file, w, h in FONTS:
        data = glyph_bytes(f"{src}/lib/fonts/{file}")
        if len(data) != 256 * h:
            sys.exit(f"gen-fonts: {file}: {len(data)} bytes, expected {256 * h}")
        out.append(f"pub const {name}_w: u8 = {w};")
        out.append(f"pub const {name}_h: u8 = {h};")
        out.append(f"pub const {name}_rows = [_]u8{{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
