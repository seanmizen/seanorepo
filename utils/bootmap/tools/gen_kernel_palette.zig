//! Print kernel/bootmap_palette.h: the palettes of src/render/color.zig as
//! C tables, for the kernel, which has no floating point.
//!
//!   zig build gen-palette > kernel/bootmap_palette.h
//!
//! For each palette colour, the table also holds the colour with each
//! jitter step (canvas.leafColor: shade(c, v / 200) for v in -12..12). So
//! the kernel's colours are the same as the daemon's colours.

const std = @import("std");
const bootmap = @import("bootmap");

pub fn main(init: std.process.Init) !void {
    var buf: [64 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buf);
    const w = &stdout.interface;
    const pals = bootmap.color.palettes;
    var max_stops: usize = 0;
    for (pals) |p| max_stops = @max(max_stops, p.stops.len);

    try w.print(
        \\/* SPDX-License-Identifier: GPL-2.0 */
        \\/* GENERATED by tools/gen_kernel_palette.zig from src/render/color.zig.
        \\ * Do not edit. Regenerate: zig build gen-palette > kernel/bootmap_palette.h */
        \\#ifndef BOOTMAP_PALETTE_H
        \\#define BOOTMAP_PALETTE_H
        \\
        \\#define BOOTMAP_PALETTES {d}
        \\#define BOOTMAP_PAL_STOPS {d}
        \\#define BOOTMAP_JITTER_MAX 12
        \\
        \\static const char *const bootmap_pal_names[BOOTMAP_PALETTES] = {{
        \\
    , .{ pals.len, max_stops });
    for (pals) |p| try w.print("\t\"{s}\",\n", .{p.name});
    try w.writeAll("};\n\nstatic const unsigned char bootmap_pal_len[BOOTMAP_PALETTES] = {\n\t");
    for (pals) |p| try w.print("{d}, ", .{p.stops.len});
    try w.writeAll("\n};\n\n/* [palette][stop][v + 12]: the stop with lightness shade v / 200. */\n");
    try w.writeAll("static const u32 bootmap_pal_shade[BOOTMAP_PALETTES][BOOTMAP_PAL_STOPS][25] = {\n");
    for (pals) |p| {
        try w.writeAll("\t{\n");
        for (0..max_stops) |si| {
            try w.writeAll("\t\t{ ");
            for (0..25) |k| {
                const v: i32 = @as(i32, @intCast(k)) - 12;
                const c: u32 = if (si < p.stops.len)
                    (if (v == 0) p.stops[si] else bootmap.color.shade(p.stops[si], @as(f32, @floatFromInt(v)) / 200))
                else
                    0;
                try w.print("0x{x:0>6}, ", .{c});
            }
            try w.writeAll("},\n");
        }
        try w.writeAll("\t},\n");
    }
    try w.writeAll("};\n\n#endif\n");
    try w.flush();
}
